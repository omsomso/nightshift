// A subprocess protocol fixture, not a model or an alternative Codex runtime.
import { createInterface } from 'node:readline';
import { randomUUID } from 'node:crypto';
import { appendFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const mode = process.argv[2] ?? 'normal';
let initialized = false;
let threadId;
let currentTurn;
const send = value => process.stdout.write(JSON.stringify(value) + '\n');
const response = (id, result) => send({ id, result });
const notify = (method, params) => send({ method, params });
const rpcError = (id, message) => send({ id, error: { code: -32000, message } });

createInterface({ input: process.stdin }).on('line', line => {
  const m = JSON.parse(line);
  if (m.method === 'initialize') {
    if (mode === 'guarded') {
      const leaked = Object.keys(process.env).filter(name => name.startsWith('OPENAI_') || name === 'CODEX_API_KEY');
      if (leaked.length) return rpcError(m.id, `Billing variables leaked: ${leaked.join(', ')}`);
      if (!process.argv.includes('forced_login_method="chatgpt"')) return rpcError(m.id, 'Expected forced ChatGPT login');
    }
    if (mode === 'malformed') return process.stdout.write('this is not JSON\n');
    if (mode === 'rpc-error') return rpcError(m.id, 'Fixture initialization failed');
    if (mode === 'rpc-timeout') return;
    if (mode === 'oversize') return process.stdout.write('x'.repeat(5000));
    return response(m.id, { userAgent: 'nightshift-fixture' });
  }
  if (m.method === 'initialized') { initialized = true; return; }
  if (!initialized) return rpcError(m.id, 'Not initialized');
  if (m.method === 'account/read') {
    if (mode === 'api-key-account') return response(m.id, { account: { type: 'apiKey' }, requiresOpenaiAuth: true });
    return response(m.id, { account: { type: 'chatgpt', email: 'private@example.com', planType: 'plus' }, requiresOpenaiAuth: true });
  }
  if (['thread/start', 'thread/resume'].includes(m.method)) {
    // Values from the schema generated by codex-cli 0.162.1.
    if (!['read-only', 'workspace-write'].includes(m.params.sandbox) || m.params.approvalPolicy !== 'never' || m.params.modelProvider !== 'openai') {
      return rpcError(m.id, 'Expected read-only policy');
    }
    threadId = m.params.threadId ?? `thread-${randomUUID()}`;
    return response(m.id, { modelProvider: mode === 'other-provider' ? 'ollama' : 'openai',
      thread: { id: threadId, status: { type: mode === 'active' ? 'active' : 'idle' } } });
  }
  if (m.method === 'turn/interrupt') {
    if (process.env.FIXTURE_MARKER) appendFileSync(process.env.FIXTURE_MARKER, `interrupt ${m.params.turnId}\n`);
    return response(m.id, {});
  }
  if (m.method !== 'turn/start') return rpcError(m.id, `Unexpected method ${m.method}`);
  if (m.params.effort !== undefined && !['low', 'medium', 'high'].includes(m.params.effort)) return rpcError(m.id, `Unsupported effort ${m.params.effort}`);
  const policy = m.params.sandboxPolicy;
  const edit = policy?.type === 'workspaceWrite' && policy.networkAccess === false;
  if (!(policy?.type === 'readOnly' || edit) || m.params.approvalPolicy !== 'never') return rpcError(m.id, 'Expected read-only or no-network workspace-write turn');
  currentTurn = `turn-${randomUUID()}`;
  if (mode === 'disconnect') return process.exit(3);
  if (mode === 'start-stall') return;
  if (mode !== 'early') response(m.id, { turn: { id: currentTurn, status: 'inProgress' } });
  if (mode === 'stall') return;
  if (mode === 'approval') {
    return send({ id: 'approval-1', method: 'item/commandExecution/requestApproval',
      params: { threadId, turnId: currentTurn, itemId: 'cmd-1', startedAtMs: 0, command: 'touch build.log', reason: 'Fixture needs permission.' } });
  }
  const ids = { threadId, turnId: currentTurn };
  const isReview = m.params.outputSchema.required.includes('passed');
  if (edit && !isReview) {
    const n = /Task (\d+) of/.exec(m.params.input[0].text)?.[1] ?? 'x';
    mkdirSync(join(m.params.cwd, 'notes'), { recursive: true });
    writeFileSync(join(m.params.cwd, 'notes', `task-${n}.txt`), `${process.env.FIXTURE_EDIT_CONTENT ?? 'done'} by codex fixture\n`);
  }
  const isPlanner = m.params.outputSchema.required.includes('tasks');
  const result = isPlanner ? { id: 'Fixture Notes!', brief: 'Write two notes.', checks: ['node check.js'], allowedPaths: ['notes/'], notes: '',
      tasks: [{ id: 'note-one', title: 'Write note one', acceptance: 'A first note exists.', difficulty: 'low', difficultyReason: 'One small file.' }, { id: 'note-two', title: 'Write note two', acceptance: 'A second note exists.', difficulty: 'high', difficultyReason: 'Pretend this is subtle.' }] }
    : isReview ? { passed: true, reason: 'Fixture review only.' }
    : { summary: 'Fixture résumé 🦉', evidence: ['fixture:README.md'] };
  notify('turn/completed', { threadId: 'unrelated-thread', turn: { id: currentTurn, status: 'completed' } });
  notify('turn/completed', { threadId, turn: { id: 'unrelated-turn', status: 'failed' } });
  // Several small deltas that the adapter must merge into one output event.
  notify('item/agentMessage/delta', { ...ids, itemId: 'message-1', delta: 'Ré' });
  notify('item/agentMessage/delta', { ...ids, itemId: 'message-1', delta: 'sumé ' });
  const usage = (input, cached, output, reasoning) => ({ inputTokens: input, cachedInputTokens: cached, outputTokens: output,
    reasoningOutputTokens: reasoning, totalTokens: input + output });
  notify('thread/tokenUsage/updated', { ...ids, tokenUsage: { last: usage(100, 40, 10, 5), total: usage(100, 40, 10, 5) } });
  notify('thread/tokenUsage/updated', { threadId, turnId: 'unrelated-turn', tokenUsage: { last: usage(9999, 0, 9999, 0), total: usage(9999, 0, 9999, 0) } });
  notify('thread/tokenUsage/updated', { ...ids, tokenUsage: { last: usage(200, 150, 20, 0), total: usage(300, 190, 30, 5) } });
  const delta = Buffer.from(JSON.stringify({ method: 'item/agentMessage/delta', params: { ...ids, itemId: 'message-1', delta: '🦉' } }) + '\n');
  // Deliberately split inside an UTF-8 code point and inside the JSONL framing.
  const split = delta.indexOf(Buffer.from('🦉')) + 1;
  process.stdout.write(delta.subarray(0, split));
  setTimeout(() => {
    process.stdout.write(delta.subarray(split));
    notify('item/completed', { ...ids, item: { id: 'message-1', type: 'agentMessage',
      text: mode === 'bad-output' ? 'not JSON' : JSON.stringify(result) } });
    notify('turn/completed', { threadId, turn: { id: currentTurn,
      status: mode === 'failed-turn' ? 'failed' : 'completed', error: mode === 'failed-turn' ? { message: 'Fixture failure' } : null } });
    if (mode === 'early') response(m.id, { turn: { id: currentTurn, status: 'inProgress' } });
  }, 5);
});
